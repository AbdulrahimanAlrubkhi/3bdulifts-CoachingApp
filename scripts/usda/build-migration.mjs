// Builds supabase/migrations/0008_usda_foods.sql from the curated list in foods.mjs.
// Values come straight from the USDA FoodData Central SR Legacy CSV files (public domain):
//   https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip
// Usage: node scripts/usda/build-migration.mjs <folder with food.csv and food_nutrient.csv>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FOODS } from "./foods.mjs";

const dir = process.argv[2];
if (!dir) throw new Error("Pass the folder that holds the extracted USDA SR Legacy CSV files.");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

function parseCsv(file, onRow) {
  const text = fs.readFileSync(file, "utf8");
  let field = "", row = [], q = false, header = null;
  const push = () => { row.push(field); field = ""; };
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else q = false; }
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ",") push();
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      push();
      if (!header) header = row; else if (row.length > 1) onRow(Object.fromEntries(header.map((h, k) => [h, row[k]])));
      row = [];
    } else field += c;
  }
}

// ── checks on the curated list ──
const CATEGORIES = ["grains", "protein", "dairy", "legumes", "vegetables", "fruit", "nuts", "fats", "sweets", "drinks", "dishes", "fast_food"];
const seedSql = fs.readFileSync(path.join(root, "supabase/migrations/0003_seed_foods.sql"), "utf8");
const seedNames = new Set();
for (const m of seedSql.matchAll(/^\s*\('([^']*)',\s*'([^']*)',/gm)) { seedNames.add(m[1]); seedNames.add(m[2].toLowerCase()); }
const seen = { id: new Set(), ar: new Set(), en: new Set() };
for (const [id, cat, ar, en] of FOODS) {
  if (!CATEGORIES.includes(cat)) throw new Error(`Unknown category ${cat} for ${en}`);
  if (seen.id.has(id) || seen.ar.has(ar) || seen.en.has(en.toLowerCase())) throw new Error(`Duplicate in list: ${id} ${en}`);
  if (seedNames.has(ar) || seedNames.has(en.toLowerCase())) throw new Error(`Already in the 0003 seed: ${en} / ${ar}`);
  seen.id.add(id); seen.ar.add(ar); seen.en.add(en.toLowerCase());
}

// ── read USDA values ──
const wanted = new Set(FOODS.map((f) => String(f[0])));
const desc = new Map();
parseCsv(path.join(dir, "food.csv"), (r) => { if (wanted.has(r.fdc_id)) desc.set(r.fdc_id, r.description); });
const NUTRIENTS = { 1008: "kcal", 1003: "protein", 1005: "carbs", 1004: "fat", 1079: "fiber" };
const values = new Map();
parseCsv(path.join(dir, "food_nutrient.csv"), (r) => {
  const key = NUTRIENTS[r.nutrient_id];
  if (!key || !wanted.has(r.fdc_id)) return;
  if (!values.has(r.fdc_id)) values.set(r.fdc_id, {});
  values.get(r.fdc_id)[key] = Number(r.amount);
});

const sq = (s) => (s == null || s === "" ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const r1 = (n) => Math.round((n ?? 0) * 10) / 10;
const lines = FOODS.map(([id, cat, ar, en, g, sAr, sEn, aliases]) => {
  const v = values.get(String(id));
  const d = desc.get(String(id));
  if (!v || !d || v.kcal == null || v.protein == null) throw new Error(`FDC ${id} (${en}) missing from the USDA files`);
  const source = `USDA FoodData Central SR Legacy, FDC ${id}: ${d}`;
  return `  (${[sq(ar), sq(en), sq(cat), r1(v.kcal), r1(v.protein), r1(v.carbs), r1(v.fat), r1(v.fiber), g ?? "null", sq(sAr), sq(sEn), sq(aliases), sq(source)].join(", ")})`;
});

const sql = `-- 0008: ${FOODS.length} foods from USDA FoodData Central (SR Legacy, public domain), values per 100 g (drinks per 100 ml).
-- Generated by scripts/usda/build-migration.mjs from scripts/usda/foods.mjs — edit those, not this file.
-- Adds only foods (or the raw/cooked state of a food) that the 0003 seed does not have, so each
-- common food now has a "raw / dry" and a "cooked" choice where people weigh it both ways.
-- Also: foods.source (where the values come from) and foods.aliases (extra search words, e.g. Gulf dialect).

alter table foods add column if not exists source text;
alter table foods add column if not exists aliases text;
comment on column foods.source is 'Where the nutrition values come from (null = coach-entered or the original seed).';
comment on column foods.aliases is 'Extra words that find this food in search (dialect, other spellings). Not shown.';

-- Dialect words for existing seed foods so search finds them the way clients type.
update foods set aliases = v.aliases
from (values
  ('White rice, cooked', 'عيش رز'), ('Basmati rice, cooked', 'عيش رز'), ('Brown rice, cooked', 'عيش رز'),
  ('White rice, raw', 'عيش رز'), ('Pasta, cooked', 'مكرونه باستا'), ('Potato, boiled', 'بطاط بطاطا'),
  ('Sweet potato, baked', 'فندال'), ('Chicken breast, grilled', 'دياي'), ('Chicken breast, raw', 'دياي'),
  ('Chicken thigh, grilled, skinless', 'دياي'), ('Roast chicken, with skin', 'دياي'),
  ('Ground beef 80/20, cooked', 'قيمة كيمة'), ('Shrimp, cooked', 'جمبري ربيان'),
  ('Kingfish (kanad), grilled', 'كنعت سمك'), ('Hamour (grouper), grilled', 'سمك'),
  ('Chickpeas, boiled', 'نخي نخج'), ('Lentils, boiled', 'دال'), ('Zucchini', 'قرع كوسه'),
  ('Eggplant, cooked', 'بيذنجان'), ('Cauliflower, cooked', 'زهرة'), ('Laban, full fat', 'روب'),
  ('Laban, low fat', 'روب'), ('Yogurt, full fat', 'روب'), ('Tea with sugar', 'شاهي'), ('Karak tea', 'شاهي')
) as v(name_en, aliases)
where foods.is_global and foods.name_en = v.name_en and foods.aliases is null;

insert into foods (name_ar, name_en, category, kcal_100g, protein_100g, carbs_100g, fat_100g, fiber_100g,
                   serving_g, serving_ar, serving_en, aliases, source, is_global, is_estimate)
select v.*, true, false
from (values
${lines.join(",\n")}
) as v(name_ar, name_en, category, kcal_100g, protein_100g, carbs_100g, fat_100g, fiber_100g,
       serving_g, serving_ar, serving_en, aliases, source)
where not exists (select 1 from foods f where f.is_global and f.name_en = v.name_en);
`;

const out = path.join(root, "supabase/migrations/0008_usda_foods.sql");
fs.writeFileSync(out, sql);
console.log(`wrote ${path.relative(root, out)} with ${FOODS.length} foods`);
